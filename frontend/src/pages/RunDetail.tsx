/** Called for every `run.log` SSE event: append to the cached log (if this run's log is loaded). */
export function appendRunLog(qc: QueryClient, id: number, entry: RunLogEntry): void {
  qc.setQueryData<RunLogEntry[]>(["runlog", id], (old) =>
    old === undefined || old.some((e) => e.seq === entry.seq) ? old : [...old, entry],
  );
}

const KIND_LABEL: Record<string, string> = {
  system: "start",
  text: "agent",
  tool: "tool",
  tool_result: "output",
  limit: "limits",
  result: "end",
  error: "error",
  surplus: "surplus",
};

const LONG = 400;

function EntryText({ text, muted }: { text: string; muted: boolean }) {
  const [open, setOpen] = useState(false);
  const cls = `whitespace-pre-wrap break-words ${muted ? "muted" : ""}`;
  if (text.length <= LONG) return <span className={cls}>{text}</span>;
  return (
    <span className={cls}>
      {open ? text : `${text.slice(0, 240).trimEnd()} …`}{" "}
      <button className="underline muted" onClick={() => setOpen(!open)} aria-expanded={open}>
        {open ? "show less" : `show all (${text.length} chars)`}
      </button>
    </span>
  );
}

function LogView({ entries, live }: { entries: RunLogEntry[]; live: boolean }) {
  const box = useRef<HTMLDivElement>(null);
  const stick = useRef(true);
  useEffect(() => {
    const el = box.current;
    if (el && stick.current) el.scrollTop = el.scrollHeight;
  }, [entries.length]);
  return (
    <div
      ref={box}
      className="max-h-[60vh] overflow-auto p-3 font-mono text-xs"
      onScroll={(e) => {
        const el = e.currentTarget;
        stick.current = el.scrollHeight - el.scrollTop - el.clientHeight < 40;
      }}
      role="log"
      aria-live={live ? "polite" : "off"}
      aria-label="Run log"
    >
      {entries.length === 0 && <p className="muted">No output yet.</p>}
      {entries.map((e) => (
        <div key={e.seq} className="grid grid-cols-[5.5rem_4.5rem_1fr] gap-2 py-0.5">
          <span className="muted tabular-nums">{new Date(e.ts).toLocaleTimeString()}</span>
          <span style={{ color: e.is_error ? "var(--status-critical)" : "var(--text-secondary)" }}>
            {e.is_error ? "▲ " : ""}
            {KIND_LABEL[e.kind] ?? e.kind}
          </span>
          <EntryText text={e.text} muted={e.kind === "tool_result"} />
        </div>
      ))}
    </div>
  );
}

function Fact({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      <dt className="text-xs muted">{label}</dt>
      <dd className="tabular-nums">{children}</dd>
    </div>
  );
}

function Report({ run }: { run: RunDetail }) {
  const r = run.report;
  if (!r) return null;
  return (
    <section className="card space-y-3 p-4 text-sm" aria-label="Report">
      <h2 className="text-sm font-medium">
        Report{" "}
        <span className="text-xs font-normal muted">
          ({run.report_source === "agent" ? "from the agent" : run.report_source === "repaired" ? "repaired" : "generated by Surplus"})
        </span>
      </h2>
      <p className="whitespace-pre-wrap">{r.summary}</p>
      <div className="grid gap-4 md:grid-cols-2">
        <div>
          <h3 className="text-xs muted">Done</h3>
          <ul className="ml-4 list-disc">{(r.done ?? []).map((d, i) => <li key={i}>{d}</li>)}</ul>
        </div>
        <div>
          <h3 className="text-xs muted">Not done</h3>
          {(r.not_done ?? []).length === 0 ? (
            <p className="muted">—</p>
          ) : (
            <ul className="ml-4 list-disc">{(r.not_done ?? []).map((d, i) => <li key={i}>{d}</li>)}</ul>
          )}
        </div>
      </div>
      {(r.questions ?? []).length > 0 && (
        <div>
          <h3 className="text-xs muted">Questions for you (answering them arrives in Phase 5; see the run report)</h3>
          <ul className="space-y-1">
            {(r.questions ?? []).map((q) => (
              <li key={q.id}>
                <strong>{q.id}</strong> {q.text}
                {(q.options ?? []).length > 0 && (
                  <span className="muted">
                    {" "}
                    — {(q.options ?? []).join(" / ")}
                    {q.recommended ? ` (recommended: ${q.recommended})` : ""}
                  </span>
                )}
              </li>
            ))}
          </ul>
        </div>
      )}
      {(r.next_suggestions ?? []).length > 0 && (
        <div>
          <h3 className="text-xs muted">Suggestions (added to the backlog as “proposed”)</h3>
          <ul className="ml-4 list-disc">
            {(r.next_suggestions ?? []).map((s, i) => (
              <li key={i}>
                ~{s.size} {s.title}
                {s.why ? <span className="muted"> — {s.why}</span> : null}
              </li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );
}

function Diff({ id }: { id: number }) {
  const diff = useQuery({ queryKey: ["rundiff", id], queryFn: () => api.runDiff(id) });
  if (diff.error) return <p role="alert">▲ {diff.error.message}</p>;
  if (!diff.data) return <p className="text-xs muted">Loading diff…</p>;
  if (!diff.data.text) return <p className="text-xs muted">No changes.</p>;
  return (
    <pre className="max-h-[70vh] overflow-auto p-3 text-xs" aria-label="Diff">
      {diff.data.text.split("\n").map((line, i) => (
        <div
          key={i}
          style={{
            color: line.startsWith("+") && !line.startsWith("+++")
              ? "var(--status-good)"
              : line.startsWith("-") && !line.startsWith("---")
                ? "var(--status-critical)"
                : line.startsWith("@@")
                  ? "var(--focus)"
                  : undefined,
          }}
        >
          {line || " "}
        </div>
      ))}
      {diff.data.truncated && <div className="muted">… truncated</div>}
    </pre>
  );
}

const WHY: Record<string, string> = {
  budget_exhausted: "it reached its 5-hour hard stop",
  max_turns: "it used all its turns",
  timeout: "it reached its time limit",
  user_active: "you started working, and you have priority (kill switch)",
  paused: "you paused Surplus",
};

/** The run stopped at a limit: ask the user whether it may go on, and how far (ADR 0008). */
function ContinuePanel({ run }: { run: RunDetail }) {
  const cap = run.cap_five_hour_pct ?? 85;
  const [newCap, setNewCap] = useState(Math.min(100, run.exit_reason === "budget_exhausted" ? cap + 5 : cap));
  const go = useMutation({
    mutationFn: () => api.continueRun(run.id, newCap),
    onSuccess: (child) => navigate(`/runs/${child.id}`),
  });
  const err = go.error instanceof ApiError ? go.error : null;
  return (
    <section className="card space-y-2 p-4 text-sm" aria-label="Permission to continue" role="region">
      <h2 className="font-medium">
        <span aria-hidden style={{ color: "var(--status-warning)" }}>▲</span> The agent stopped because{" "}
        {WHY[run.exit_reason ?? ""] ?? "it hit a limit"}. Continue?
      </h2>
      <p className="text-xs muted">
        Its work so far is committed, tested and reported below. Continuing resumes the same session on{" "}
        <code>{run.branch}</code> with a new 5-hour hard stop; the weekly cap stays. Or merge or discard as usual.
      </p>
      <div className="flex flex-wrap items-end gap-3">
        <label className="flex flex-col text-xs muted">
          New 5-hour hard stop: {newCap}%
          <input
            type="range"
            min={Math.min(100, Math.floor(cap))}
            max={100}
            step={1}
            value={newCap}
            onChange={(e) => setNewCap(Number(e.target.value))}
            className="mt-1 w-56"
          />
        </label>
        <button className="btn" onClick={() => go.mutate()} disabled={go.isPending}>
          {go.isPending ? "Starting…" : `Allow and continue to ${newCap}%`}
        </button>
      </div>
      {newCap >= 98 && (
        <p className="text-xs">
          <span aria-hidden style={{ color: "var(--status-warning)" }}>▲</span> At {newCap}% you may have almost
          nothing left for your own work until the window resets.
        </p>
      )}
      {go.error && (
        <p role="alert">▲ {err?.problems.length ? err.problems.join("; ") : go.error.message}</p>
      )}
    </section>
  );
}

export function RunDetailPage({ id }: { id: number }) {
  const qc = useQueryClient();
  const run = useQuery({ queryKey: ["run", id], queryFn: () => api.run(id) });
  const log = useQuery({ queryKey: ["runlog", id], queryFn: () => api.runLog(id), staleTime: Infinity });
  const [showDiff, setShowDiff] = useState(false);
  const action = useMutation({
    mutationFn: (a: "stop" | "cancel" | "merge" | "discard") => api.runAction(id, a),
    onSettled: () => {
      void qc.invalidateQueries({ queryKey: ["run", id] });
      void qc.invalidateQueries({ queryKey: ["runs"] });
    },
  });

  if (run.error) {
    return (
      <p className="card p-4 text-sm" role="alert">
        {run.error instanceof ApiError && run.error.status === 404 ? `No run ${id}.` : run.error.message}
      </p>
    );
  }
  const r = run.data;
  if (!r) return <p className="text-sm muted">Loading…</p>;
  const active = isActive(r);
  const budget = r.budget_pct;
  const spent = r.spent_pct_est;

  return (
    <div className="space-y-4">
      <div>
        <p className="text-xs muted">
          <Link href="/projects">Projects</Link> / <Link href={`/projects/${encodeURIComponent(r.project_id)}/runs`}>{r.project_id}</Link> /
        </p>
        <div className="flex flex-wrap items-baseline gap-3">
          <h1 className="text-lg font-semibold">
            Run {r.name}
            <span className="font-normal muted"> · {r.task_id} {r.task_title}</span>
          </h1>
          <RunStateBadge run={r} />
          <div className="ml-auto flex gap-2">
            {active && (
              <>
                <button className="btn" onClick={() => action.mutate("stop")} disabled={action.isPending}
                  title="Ask the agent to stop; its work is still committed, tested and reported">
                  Stop and report
                </button>
                <button
                  className="btn"
                  onClick={() => confirm("Cancel now, without a report? The branch is not kept.") && action.mutate("cancel")}
                  disabled={action.isPending}
                >
                  Cancel
                </button>
              </>
            )}
            {r.state === "awaiting_feedback" && (
              <>
                <button
                  className="btn"
                  disabled={action.isPending || r.commits === 0}
                  title={r.commits === 0 ? "No commits to merge" : `Merge into ${r.base_branch ?? "the current branch"}`}
                  onClick={() => confirm(`Merge ${r.branch} into ${r.base_branch ?? "the current branch"}?`) && action.mutate("merge")}
                >
                  Merge branch
                </button>
                <button
                  className="btn"
                  disabled={action.isPending}
                  onClick={() => confirm(`Discard ${r.branch ?? "this run"}? The branch is deleted.`) && action.mutate("discard")}
                >
                  Discard
                </button>
              </>
            )}
          </div>
        </div>
        {action.error && (
          <p role="alert" className="mt-1 text-sm">
            <span aria-hidden style={{ color: "var(--status-critical)" }}>▲</span> {action.error.message}
          </p>
        )}
        {r.parent_run_id != null && (
          <p className="mt-1 text-xs muted">
            Continues <Link href={`/runs/${r.parent_run_id}`} className="underline">r{r.parent_run_id}</Link> (allowed
            by you).
          </p>
        )}
        {r.continued_by != null && (
          <p className="mt-1 text-xs muted">
            Continued in <Link href={`/runs/${r.continued_by}`} className="underline">r{r.continued_by}</Link>.
          </p>
        )}
        {r.error && (
          <p role="alert" className="mt-1 text-sm">
            <span aria-hidden style={{ color: "var(--status-critical)" }}>■</span> {r.error}
          </p>
        )}
      </div>

      <dl className="card grid grid-cols-2 gap-3 p-4 text-sm md:grid-cols-4">
        <Fact label="Model">
          {r.model}
          {r.effort ? ` · ${r.effort} effort` : ""} · max {r.max_turns} turns
        </Fact>
        <Fact label="Branch">
          <code className="text-xs">{r.branch ?? "—"}</code>
          {r.base_branch && <span className="text-xs muted"> from {r.base_branch}</span>}
        </Fact>
        <Fact label="Turns · commits">
          {r.num_turns ?? "—"} · {r.commits}
        </Fact>
        <Fact label="Tests (run by Surplus)">{r.verified_tests ?? "—"}</Fact>
        <Fact label="Spend (5-hour window)">
          {spent != null ? `${spent.toFixed(1)} pp` : "—"}
          {budget != null && <span className="text-xs muted"> of {budget.toFixed(0)} pp room</span>}
          {r.cap_five_hour_pct != null && (
            <span className="block text-xs muted">hard stop at {r.cap_five_hour_pct.toFixed(0)}%</span>
          )}
        </Fact>
        <Fact label="Ended because">{r.exit_reason?.replaceAll("_", " ") ?? "—"}</Fact>
        <Fact label="Started">{r.started_at ? since(r.started_at) : "—"}</Fact>
        <Fact label="Ended">{r.ended_at ? since(r.ended_at) : "—"}</Fact>
      </dl>
      {r.base_dirty && (
        <p className="text-xs">
          <span aria-hidden style={{ color: "var(--status-warning)" }}>▲</span> The project had uncommitted changes when
          this run started; the agent worked from the last commit.
        </p>
      )}

      {r.can_continue && <ContinuePanel run={r} />}

      <Report run={r} />

      <section className="card" aria-label="Live log">
        <h2 className="border-b px-4 py-2 text-sm font-medium" style={{ borderColor: "var(--border)" }}>
          Log {active && <span className="text-xs font-normal muted">· live</span>}
        </h2>
        <LogView entries={log.data ?? []} live={active} />
      </section>

      {r.test_output && (
        <details className="card">
          <summary className="cursor-pointer px-4 py-2 text-sm">Test output</summary>
          <pre className="max-h-[50vh] overflow-auto p-3 text-xs">{r.test_output}</pre>
        </details>
      )}

      {r.commits > 0 && (
        <details className="card" onToggle={(e) => setShowDiff((e.target as HTMLDetailsElement).open)}>
          <summary className="cursor-pointer px-4 py-2 text-sm">Diff ({r.commits} commit{r.commits === 1 ? "" : "s"})</summary>
          {showDiff && <Diff id={id} />}
        </details>
      )}
    </div>
  );
}
